// Prepares the app folder before running or building:
//  - copies React into app/vendor
//  - copies the fonts into app/fonts and writes app/fonts.css
//  - bundles the two screen files (Main.dc.html, Thumb.dc.html) into app/screens.js
// Run with:  node tools/prepare.js   (npm start and npm run dist do this for you)

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const app = path.join(root, 'app');
const nm = path.join(root, 'node_modules');

function copy(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

// 1. React
copy(path.join(nm, 'react/umd/react.production.min.js'), path.join(app, 'vendor/react.production.min.js'));
copy(path.join(nm, 'react-dom/umd/react-dom.production.min.js'), path.join(app, 'vendor/react-dom.production.min.js'));

// 1b. PDF previews (pdf.js)
copy(path.join(nm, 'pdfjs-dist/build/pdf.min.js'), path.join(app, 'vendor/pdf.min.js'));
copy(path.join(nm, 'pdfjs-dist/build/pdf.worker.min.js'), path.join(app, 'vendor/pdf.worker.min.js'));

// 2. Fonts: [package, CSS family name, weights]
const fonts = [
  ['figtree', 'Figtree', [400, 500, 600, 700]],
  ['dancing-script', 'Dancing Script', [400, 600]],
  ['great-vibes', 'Great Vibes', [400]],
  ['permanent-marker', 'Permanent Marker', [400]],
  ['special-elite', 'Special Elite', [400]],
  ['pacifico', 'Pacifico', [400]],
  ['amatic-sc', 'Amatic SC', [700]],
  ['caveat', 'Caveat', [500]],
  ['patrick-hand', 'Patrick Hand', [400]],
  ['lobster', 'Lobster', [400]],
  ['playfair-display', 'Playfair Display', [500, 700]],
  ['quicksand', 'Quicksand', [500, 700]],
  ['atkinson-hyperlegible', 'Atkinson Hyperlegible', [400, 700]],
  ['lexend', 'Lexend', [400, 600]]
];
let css = '/* Generated by tools/prepare.js */\n';
for (const [pkg, family, weights] of fonts) {
  const dir = path.join(nm, '@fontsource', pkg, 'files');
  for (const w of weights) {
    for (const subset of ['latin', 'latin-ext']) {
      const file = `${pkg}-${subset}-${w}-normal.woff2`;
      if (!fs.existsSync(path.join(dir, file))) continue;
      copy(path.join(dir, file), path.join(app, 'fonts', file));
      const range = subset === 'latin'
        ? 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD'
        : 'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF';
      css += `@font-face{font-family:'${family}';font-style:normal;font-weight:${w};font-display:swap;src:url(fonts/${file}) format('woff2');unicode-range:${range}}\n`;
    }
  }
}
css += "@font-face{font-family:'OpenDyslexic';font-style:normal;font-weight:400;font-display:swap;src:url(OpenDyslexic-Regular.woff) format('woff')}\n";
fs.writeFileSync(path.join(app, 'fonts.css'), css);

// 3. Screens
const sources = {};
for (const name of ['Main', 'Thumb']) {
  let src = fs.readFileSync(path.join(app, name + '.dc.html'), 'utf8');
  // The canvas stored the OpenDyslexic font and old textures online; use local copies / nothing.
  src = src.replace(/url\(\/_blob\/0b811c100bc1a2590aa7c03903783c46\)/g, 'url(OpenDyslexic-Regular.woff)');
  src = src.replace(/url\(\/_blob\/[0-9a-f]+\)/g, 'none');
  sources[name] = src;
}
fs.writeFileSync(path.join(app, 'screens.js'), '// Generated by tools/prepare.js\nwindow.DC_SOURCES = ' + JSON.stringify(sources) + ';\n');

console.log('App folder prepared.');
